// Current: the narrow bridge between the editor page and the main process.
'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('native', {
  importMedia: call('dialog:importMedia'),
  openProjectDialog: call('dialog:openProject'),
  saveProjectDialog: call('dialog:saveProject'),
  exportPathDialog: call('dialog:exportPath'),
  message: call('dialog:message'),
  chooseImage: call('dialog:chooseImage'),
  brandLoad: call('brand:load'),
  brandSave: call('brand:save'),
  readText: call('fs:readText'),
  writeText: call('fs:writeText'),
  readBinary: call('fs:readBinary'),
  exists: call('fs:exists'),
  stat: call('fs:stat'),
  cacheWrite: call('fs:cacheWrite'),
  cachePath: call('fs:cachePath'),
  saveVoiceover: call('voiceover:save'),
  showItem: call('shell:showItem'),
  openExternal: call('shell:openExternal'),
  info: call('app:info'),
  setTitle: call('win:setTitle'),
  minimize: call('win:minimize'),
  restoreWindow: call('win:restore'),
  saveRecording: call('recording:save'),
  captionsStatus: call('captions:status'),
  captionsDownload: call('captions:download'),
  captionsTranscribe: call('captions:transcribe'),
  captionsCancel: call('captions:cancel'),
  onCaptionsProgress: (cb) => { const f = (_e, m) => cb(m); ipcRenderer.on('captions:progress', f); return () => ipcRenderer.removeListener('captions:progress', f); },
  recentList: call('recent:list'),
  recentAdd: call('recent:add'),
  recentRemove: call('recent:remove'),
  proxy: call('media:proxy'),
  exportStart: call('export:start'),
  exportFrame: call('export:frame'),
  exportFinish: call('export:finish'),
  exportCancel: call('export:cancel'),
  gstCheck: call('gst:check'),
  assistantGet: call('assistant:get'),
  assistantSet: call('assistant:set'),
  assistantSaveBundle: call('assistant:saveBundle'),
  onAssistantCall: (cb) => { ipcRenderer.removeAllListeners('assistant:call'); ipcRenderer.on('assistant:call', (_e, m) => cb(m)); },
  assistantResult: (id, out) => ipcRenderer.send('assistant:result', id, out),
  assistantReady: () => ipcRenderer.send('assistant:ready'),
  assistantKeyStatus: call('assistant:keyStatus'),
  assistantSaveKey: call('assistant:saveKey'),
  assistantRemoveKey: call('assistant:removeKey'),
  assistantPanelSend: call('assistant:panelSend'),
  assistantPanelStop: call('assistant:panelStop'),
  assistantPanelReset: call('assistant:panelReset'),
  onAssistantPanelEvent: (cb) => { ipcRenderer.removeAllListeners('assistant:panelEvent'); ipcRenderer.on('assistant:panelEvent', (_e, ev) => cb(ev)); },
  selftestFakeClaude: (turns) => ipcRenderer.invoke('selftest:fakeClaude', turns),
  selftestFakeClaudeRequests: () => ipcRenderer.invoke('selftest:fakeClaudeRequests'),
  selftestBridge: (messages, env) => ipcRenderer.invoke('selftest:bridge', messages, env),
  selftestWriteText: (file, text) => ipcRenderer.invoke('selftest:writeText', file, text),
  selftestCapture: (f) => ipcRenderer.invoke('selftest:capture', f),
  selftestMouse: (x, y) => ipcRenderer.invoke('selftest:mouse', x, y),
  selftestDone: (code) => ipcRenderer.send('selftest:done', code),
  pathForFile: (file) => webUtils.getPathForFile(file),
  // macOS menus (see main.js)
  setAppMenu: call('menu:setApp'),
  popupMenu: call('menu:popup'),
  editText: call('edit:text'),
  // macOS privacy and the screen picker (see main.js)
  mediaAccess: call('media:access'),
  openPrivacy: call('media:openPrivacy'),
  onScreenPick: (cb) => { ipcRenderer.on('screen:pick', async (_e, id, list) => ipcRenderer.send('screen:picked', id, await cb(list))); },
  onMenuRun: (cb) => { ipcRenderer.on('menu:run', (_e, id) => cb(id)); },
  onMenuEdit: (cb) => { ipcRenderer.on('menu:edit', (_e, op, id) => cb(op, id)); },
});
